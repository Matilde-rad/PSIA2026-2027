#!/usr/bin/env python3
"""Turn `terraform output -json` into inventory.ini for Ansible.

    python3 inventory.py          # runs `terraform output -json` in ../terraform
    python3 inventory.py FILE     # reads the same JSON from FILE
"""

import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TERRAFORM_DIR = HERE.parent / "terraform"
INVENTORY = HERE / "inventory.ini"

GROUP_OUTPUTS = {"master": "master_ips", "workers": "worker_ips", "build": "build_ips"}


def fail(message):
    sys.exit(f"inventory.py: {message}")


def read_outputs():
    if len(sys.argv) > 1:
        try:
            return json.loads(Path(sys.argv[1]).read_text())
        except (OSError, json.JSONDecodeError) as e:
            fail(f"cannot read {sys.argv[1]}: {e}")
    try:
        result = subprocess.run(
            ["terraform", f"-chdir={TERRAFORM_DIR}", "output", "-json"],
            capture_output=True,
            text=True,
        )
    except FileNotFoundError:
        fail("terraform not found, run this inside the mgmt container (`just mgmt`)")
    if result.returncode != 0:
        fail(f"terraform output failed:\n{result.stderr.strip()}")
    try:
        return json.loads(result.stdout)
    except json.JSONDecodeError as e:
        fail(f"terraform output is not valid JSON: {e}")


def main():
    outputs = read_outputs()
    if not outputs:
        fail("terraform has no outputs, run `terraform apply` in infra/terraform first")

    def values(name):
        return (outputs.get(name) or {}).get("value") or {}

    internal = values("internal_ips")
    lines = []
    written = []
    for group, output in GROUP_OUTPUTS.items():
        lines.append(f"[{group}]")
        for host, public_ip in sorted(values(output).items()):
            if not public_ip:
                fail(
                    f"{host} has no public IP (is the VM stopped?). Start it, run "
                    "`terraform apply -refresh-only` in infra/terraform, then rerun"
                )
            if not internal.get(host):
                fail(f"{host} has no internal IP in the internal_ips output")
            lines.append(f"{host} ansible_host={public_ip} internal_ip={internal[host]}")
            written.append(host)
        lines.append("")
    if not written:
        fail("the terraform outputs list no hosts, run `terraform apply` first")
    lines += ["[cluster:children]", "master", "workers", ""]

    header = ["# Generated by inventory.py, rerun it when the public IPs change.", ""]
    INVENTORY.write_text("\n".join(header + lines))
    print(f"wrote {INVENTORY.name}: {', '.join(written)}")


if __name__ == "__main__":
    main()
